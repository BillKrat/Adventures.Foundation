using System.Text;
using System.Text.RegularExpressions;
using Npgsql;

namespace Adventures.Data.NQuad;

/// <summary>
/// The hybrid-dictionary layout of the N-Quad store (decision: <c>ai-research-blog/docs/Claude-decision-2026-11-quad-storage.md</c>). A subject, a predicate, a graph and an object that is an IRI are
/// rows of a dictionary table and the quad row holds their integer ids; every other object (a literal: title, slug, date, body) stays inline as text in the quad row. The W3C text
/// never shows: this class takes and returns <see cref="NQuad"/> with full text, expanding ids through a bounded <see cref="TermCache"/> and the dictionary, so nothing above the store changes.
/// </summary>
/// <remarks>
/// Whether an object goes to the dictionary is decided by <see cref="IsIri"/>, a pure function of its text, used the same way on write and on query, so what was written is always found.
/// It only chooses where the text is kept: an object that merely looks like an address round-trips exactly all the same. Terms are never rewritten or removed (the dictionary is append-only),
/// so a cached id stays valid for the life of the database, which is also why <see cref="PurgeAsync"/> empties the quads and leaves the dictionary.
/// Tables are <c>{prefix}_terms</c> and <c>{prefix}_quads</c>; the prefix is validated because it is interpolated into SQL.
/// </remarks>
public sealed partial class NpgsqlDictionaryNQuadStore : INQuadStore, INQuadStoreInitializer
{
    public const string DefaultPrefix = "dq";

    /// <summary>The longest term, in UTF-8 bytes, that goes into the dictionary (its unique index cannot hold much more than 2.7 KB). A longer subject, predicate or graph is refused; a longer object is simply a literal.</summary>
    public const int MaxTermBytes = 2000;

    private const int LiteralIndexLength = 255;

    [GeneratedRegex("^[a-z_][a-z0-9_]{0,40}$")]
    private static partial Regex PrefixRegex();

    private readonly string _connectionString;
    private readonly string _terms;
    private readonly string _quads;
    private readonly TermCache _cache;

    public NpgsqlDictionaryNQuadStore(string connectionString, string prefix = DefaultPrefix, int maxCachedTerms = 50_000)
    {
        _connectionString = connectionString ?? throw new ArgumentNullException(nameof(connectionString));
        ArgumentNullException.ThrowIfNull(prefix);
        if (!PrefixRegex().IsMatch(prefix))
        {
            throw new ArgumentException("The table prefix must be a lower-case identifier (letters, digits, underscore; at most 41 characters).", nameof(prefix));
        }

        _terms = prefix + "_terms";
        _quads = prefix + "_quads";
        _cache = new TermCache(maxCachedTerms);
    }

    /// <summary>True when the object text is kept in the dictionary: an address (<c>http://</c>, <c>https://</c> or <c>urn:</c>) short enough for the dictionary index.</summary>
    public static bool IsIri(string text) =>
        text.Length > 0 && text.Length <= MaxTermBytes
        && (text.StartsWith("http://", StringComparison.Ordinal) || text.StartsWith("https://", StringComparison.Ordinal) || text.StartsWith("urn:", StringComparison.Ordinal))
        && Encoding.UTF8.GetByteCount(text) <= MaxTermBytes;

    public async Task CreateTableAsync(CancellationToken cancellationToken = default)
    {
        var sql = $"""
            CREATE TABLE IF NOT EXISTS {_terms} (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                value text NOT NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ux_{_terms}_value ON {_terms} (value);

            CREATE TABLE IF NOT EXISTS {_quads} (
                id uuid PRIMARY KEY,
                g bigint NULL,
                s bigint NOT NULL,
                p bigint NOT NULL,
                o bigint NULL,
                lit text NULL,
                CONSTRAINT ck_{_quads}_object CHECK ((o IS NULL) <> (lit IS NULL))
            );
            CREATE INDEX IF NOT EXISTS ix_{_quads}_spg ON {_quads} (s, p, g);
            CREATE INDEX IF NOT EXISTS ix_{_quads}_pogs ON {_quads} (p, o, g, s) WHERE o IS NOT NULL;
            CREATE INDEX IF NOT EXISTS ix_{_quads}_plit ON {_quads} (p, left(lit, {LiteralIndexLength}), g) WHERE lit IS NOT NULL;
            CREATE INDEX IF NOT EXISTS ix_{_quads}_gps ON {_quads} (g, p, s);
            """;
        await using var connection = await OpenAsync(cancellationToken);
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public Task InitializeAsync(CancellationToken cancellationToken = default) => CreateTableAsync(cancellationToken);

    /// <summary>Deletes every quad. The dictionary stays: its ids are never reused, so any process's cache stays valid.</summary>
    public async Task<int> PurgeAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await OpenAsync(cancellationToken);
        await using var count = new NpgsqlCommand($"SELECT count(*) FROM {_quads}", connection);
        var rows = Convert.ToInt32(await count.ExecuteScalarAsync(cancellationToken), System.Globalization.CultureInfo.InvariantCulture);
        await using var truncate = new NpgsqlCommand($"TRUNCATE TABLE {_quads}", connection);
        await truncate.ExecuteNonQueryAsync(cancellationToken);
        return rows;
    }

    public Task<int> InsertAsync(NQuad quad, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(quad);
        return InsertManyAsync([quad], cancellationToken);
    }

    /// <summary>Inserts a batch atomically: the missing dictionary terms and the quads go in one transaction, and the cache learns the new terms only after it commits.</summary>
    public async Task<int> InsertManyAsync(IReadOnlyCollection<NQuad> quads, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(quads);
        cancellationToken.ThrowIfCancellationRequested();
        if (quads.Count == 0)
        {
            return 0;
        }

        var needed = new HashSet<string>(StringComparer.Ordinal);
        foreach (var quad in quads)
        {
            needed.Add(Term(quad.Subject, "subject"));
            needed.Add(Term(quad.Predicate, "predicate"));
            if (quad.Graph is not null)
            {
                needed.Add(Term(quad.Graph, "graph"));
            }

            if (IsIri(quad.Object))
            {
                needed.Add(quad.Object);
            }
        }

        await using var connection = await OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        var fresh = new List<(string Value, long Id)>();
        var ids = await ResolveAsync(connection, transaction, needed, create: true, fresh, cancellationToken);

        var count = quads.Count;
        var quadIds = new Guid[count];
        var g = new long?[count];
        var s = new long[count];
        var p = new long[count];
        var o = new long?[count];
        var lit = new string?[count];
        var i = 0;
        foreach (var quad in quads)
        {
            quadIds[i] = quad.Id;
            g[i] = quad.Graph is null ? null : ids[quad.Graph];
            s[i] = ids[quad.Subject];
            p[i] = ids[quad.Predicate];
            if (IsIri(quad.Object))
            {
                o[i] = ids[quad.Object];
            }
            else
            {
                lit[i] = quad.Object;
            }

            i++;
        }

        // one statement, one round trip however many quads; a duplicate id fails it and the whole transaction rolls back
        await using var insert = new NpgsqlCommand($"INSERT INTO {_quads} (id, g, s, p, o, lit) SELECT * FROM unnest(@ids, @g, @s, @p, @o, @lit)", connection, transaction);
        insert.Parameters.AddWithValue("ids", quadIds);
        insert.Parameters.AddWithValue("g", g);
        insert.Parameters.AddWithValue("s", s);
        insert.Parameters.AddWithValue("p", p);
        insert.Parameters.AddWithValue("o", o);
        insert.Parameters.AddWithValue("lit", lit);
        var inserted = await insert.ExecuteNonQueryAsync(cancellationToken);
        await transaction.CommitAsync(cancellationToken);

        foreach (var (value, id) in fresh)
        {
            _cache.Add(value, id);
        }

        return inserted;
    }

    public async Task<IReadOnlyList<NQuad>> QueryAsync(string? subject = null, string? predicate = null, string? @object = null, string? graph = null, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var wanted = new HashSet<string>(StringComparer.Ordinal);
        if (subject is not null) wanted.Add(subject);
        if (predicate is not null) wanted.Add(predicate);
        if (graph is not null) wanted.Add(graph);
        var objectIsIri = @object is not null && IsIri(@object);
        if (objectIsIri) wanted.Add(@object!);

        await using var connection = await OpenAsync(cancellationToken);
        var ids = await ResolveAsync(connection, null, wanted, create: false, null, cancellationToken);
        if (wanted.Any(term => !ids.ContainsKey(term)))
        {
            // a term nobody ever wrote cannot match any quad
            return [];
        }

        var conditions = new List<string>();
        await using var command = new NpgsqlCommand { Connection = connection };
        if (subject is not null) { conditions.Add("s = @s"); command.Parameters.AddWithValue("s", ids[subject]); }
        if (predicate is not null) { conditions.Add("p = @p"); command.Parameters.AddWithValue("p", ids[predicate]); }
        if (graph is not null) { conditions.Add("g = @g"); command.Parameters.AddWithValue("g", ids[graph]); }
        if (@object is not null)
        {
            if (objectIsIri)
            {
                conditions.Add("o = @o");
                command.Parameters.AddWithValue("o", ids[@object]);
            }
            else
            {
                // the left(...) equality lets the partial expression index (p, left(lit, 255), g) apply: a literal can be a whole post body
                conditions.Add($"lit IS NOT NULL AND left(lit, {LiteralIndexLength}) = left(@lit, {LiteralIndexLength}) AND lit = @lit");
                command.Parameters.AddWithValue("lit", @object);
            }
        }

        var where = conditions.Count == 0 ? string.Empty : "WHERE " + string.Join(" AND ", conditions);
        command.CommandText = $"SELECT id, g, s, p, o, lit FROM {_quads} {where}";
        return await ReadAsync(command, connection, cancellationToken);
    }

    public async Task<IReadOnlyList<NQuad>> QueryBySubjectsAsync(IReadOnlyCollection<string> subjects, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(subjects);
        cancellationToken.ThrowIfCancellationRequested();
        if (subjects.Count == 0)
        {
            return [];
        }

        await using var connection = await OpenAsync(cancellationToken);
        var ids = await ResolveAsync(connection, null, subjects.ToHashSet(StringComparer.Ordinal), create: false, null, cancellationToken);
        if (ids.Count == 0)
        {
            return [];
        }

        await using var command = new NpgsqlCommand($"SELECT id, g, s, p, o, lit FROM {_quads} WHERE s = ANY(@s)", connection);
        command.Parameters.AddWithValue("s", ids.Values.ToArray());
        return await ReadAsync(command, connection, cancellationToken);
    }

    public async Task<long> CountAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await OpenAsync(cancellationToken);
        await using var command = new NpgsqlCommand($"SELECT count(*) FROM {_quads}", connection);
        return Convert.ToInt64(await command.ExecuteScalarAsync(cancellationToken), System.Globalization.CultureInfo.InvariantCulture);
    }

    private async Task<NpgsqlConnection> OpenAsync(CancellationToken cancellationToken)
    {
        var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync(cancellationToken);
        return connection;
    }

    private static string Term(string value, string kind)
    {
        ArgumentNullException.ThrowIfNull(value, kind);
        if (Encoding.UTF8.GetByteCount(value) > MaxTermBytes)
        {
            throw new ArgumentException($"A {kind} longer than {MaxTermBytes} bytes cannot be stored.", kind);
        }

        return value;
    }

    /// <summary>
    /// Text to id for every wanted term: from the cache, then one round trip for the rest. With <paramref name="create"/> the missing ones are inserted first (inside the caller's transaction); the ids
    /// found or made in the database are listed in <paramref name="fresh"/> for the caller to cache once its transaction has committed (a read, with no transaction, caches them at once).
    /// </summary>
    private async Task<Dictionary<string, long>> ResolveAsync(NpgsqlConnection connection, NpgsqlTransaction? transaction, IReadOnlyCollection<string> wanted, bool create, List<(string Value, long Id)>? fresh, CancellationToken cancellationToken)
    {
        var result = new Dictionary<string, long>(StringComparer.Ordinal);
        var missing = new List<string>();
        foreach (var term in wanted)
        {
            if (_cache.TryGetId(term, out var id))
            {
                result[term] = id;
            }
            else
            {
                missing.Add(term);
            }
        }

        if (missing.Count == 0)
        {
            return result;
        }

        if (create)
        {
            await using var insert = new NpgsqlCommand($"INSERT INTO {_terms} (value) SELECT unnest(@v) ON CONFLICT (value) DO NOTHING", connection, transaction);
            insert.Parameters.AddWithValue("v", missing.ToArray());
            await insert.ExecuteNonQueryAsync(cancellationToken);
        }

        await using var select = new NpgsqlCommand($"SELECT id, value FROM {_terms} WHERE value = ANY(@v)", connection, transaction);
        select.Parameters.AddWithValue("v", missing.ToArray());
        await using var reader = await select.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            var id = reader.GetInt64(0);
            var value = reader.GetString(1);
            result[value] = id;
            if (transaction is null)
            {
                _cache.Add(value, id);
            }
            else
            {
                fresh?.Add((value, id));
            }
        }

        return result;
    }

    private async Task<IReadOnlyList<NQuad>> ReadAsync(NpgsqlCommand command, NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        var rows = new List<(Guid Id, long? G, long S, long P, long? O, string? Lit)>();
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                rows.Add((reader.GetGuid(0), reader.IsDBNull(1) ? null : reader.GetInt64(1), reader.GetInt64(2), reader.GetInt64(3), reader.IsDBNull(4) ? null : reader.GetInt64(4), reader.IsDBNull(5) ? null : reader.GetString(5)));
            }
        }

        var texts = new Dictionary<long, string>();
        var missing = new HashSet<long>();
        void Need(long? id)
        {
            if (id is not { } value || texts.ContainsKey(value))
            {
                return;
            }

            if (_cache.TryGetValue(value, out var text))
            {
                texts[value] = text;
            }
            else
            {
                missing.Add(value);
            }
        }

        foreach (var row in rows)
        {
            Need(row.G);
            Need(row.S);
            Need(row.P);
            Need(row.O);
        }

        if (missing.Count > 0)
        {
            await using var select = new NpgsqlCommand($"SELECT id, value FROM {_terms} WHERE id = ANY(@ids)", connection);
            select.Parameters.AddWithValue("ids", missing.ToArray());
            await using var reader = await select.ExecuteReaderAsync(cancellationToken);
            while (await reader.ReadAsync(cancellationToken))
            {
                var id = reader.GetInt64(0);
                var value = reader.GetString(1);
                texts[id] = value;
                _cache.Add(value, id);
            }
        }

        var result = new List<NQuad>(rows.Count);
        foreach (var row in rows)
        {
            result.Add(new NQuad(row.Id, texts[row.S], texts[row.P], row.O is { } o ? texts[o] : row.Lit!, row.G is { } g ? texts[g] : null));
        }

        return result;
    }
}
